"""Read-only opened-case RMSE decomposition; never a control headroom proof.

The only write is a requested technical JSON audit. No cases, proposals,
policies, trajectories or prospective namespaces are generated by this module.
"""
from pathlib import Path
import argparse,hashlib,json,math,statistics
from collections import Counter

ROOT=Path(__file__).resolve().parents[2]
DATA=ROOT/'results/ppo-complete-v13'
FOLDERS=('teacher-development72','headroom-finite-original-amp02-pilot12',
    'headroom-finite-original-pilot2','headroom-finite-anchor-pilot2')


def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda:stream.read(1024**2),b''):h.update(block)
    return h.hexdigest()


def percentile(values,p):
    values=sorted(values);index=(len(values)-1)*p;left=math.floor(index);right=math.ceil(index)
    return values[left]+(index-left)*(values[right]-values[left])


def read_folder(folder):
    folder=DATA/folder;protocol=json.loads((folder/'protocol.json').read_text())
    summary=json.loads((folder/'summary.json').read_text());traces={};hashes={}
    assert protocol['role']=='opened_case_causal_teacher_headroom_only' and protocol['no_fresh_case_claim']
    for name,digest in protocol['source_hashes'].items():assert sha(folder/'source'/name)==digest,('Retained source changed',name)
    for record in summary:
        key=(record['case']['id'],record['mode']);assert key not in traces
        path=folder/f'{key[0]:03d}-{key[1]}.jsonl';digest=sha(path)
        assert digest==record['raw_sha256'],('Raw trace changed',path)
        rows=[json.loads(line) for line in path.open()]
        assert len(rows)==record['ticks']==120 and not record['failed']
        assert [r['tick'] for r in rows]==list(range(120))
        for r in rows:
            assert math.isclose(r['time_s'],r['tick']*.05,abs_tol=1e-12)
            assert not r['collision'] and not r['corridor_exceeded']
        rmse=math.sqrt(sum(r['error']**2 for r in rows)/120)
        assert math.isclose(rmse,record['rmse_m'],rel_tol=1e-12,abs_tol=1e-12)
        hashes[str(path.relative_to(ROOT))]=digest;traces[key]=rows
    assert len(traces)==2*len(protocol['cases'])
    return protocol,summary,traces,dict(protocol_sha256=sha(folder/'protocol.json'),summary_sha256=sha(folder/'summary.json'),
        retained_source_snapshot_files_verified=len(protocol['source_hashes']),raw_trace_sha256=hashes)


def opportunity():
    results={}
    for name in FOLDERS:
        protocol,summary,traces,provenance=read_folder(name)
        references=[rows for (i,mode),rows in traces.items() if mode=='reference']
        teacher_runs=[rows for (i,mode),rows in traces.items() if mode=='teacher']
        rows=[r for run in teacher_runs for r in run];eligible=[r for r in rows if r['context']['eligible']]
        gaps=[];minimum_model_slacks=[];local_gains=[]
        for r in eligible:
            a=[v[0] for v in r['context']['reference_values']];b=[v[0] for v in r['context']['lqr_values']]
            gaps.append(100*(statistics.mean(b)-statistics.mean(a))/max(abs(statistics.mean(b)),1e-12))
            minimum_model_slacks.append(100*min((l-c)/max(abs(l),1e-12) for c,l in zip(a,b)))
            diag=r['teacher']
            if 'baseline_model_value' in diag:
                local_gains.append(100*(diag['baseline_model_value']-diag['selected_model_value'])/max(abs(diag['baseline_model_value']),1e-12))
        statuses=Counter(r['teacher']['solver_status'] for r in eligible)
        selected_by_time={}
        for lower,upper in ((0,10),(10,20),(20,120)):
            band=[r for r in rows if lower<=r['tick']<upper]
            selected_by_time[f'ticks_{lower}_through_{upper-1}']=dict(ticks=len(band),
                eligible=sum(r['context']['eligible'] for r in band),selected=sum(r['sequence_plan_selected'] for r in band))
        reference_rmse=statistics.mean(math.sqrt(sum(r['error']**2 for r in run)/120) for run in references)
        teacher_rmse=statistics.mean(math.sqrt(sum(r['error']**2 for r in run)/120) for run in teacher_runs)
        teacher_heading=statistics.mean(math.sqrt(statistics.mean(r['heading_error']**2 for r in run)) for run in teacher_runs)
        lqr_heading=statistics.mean(math.sqrt(statistics.mean(r['shadow_truth']['heading_error']**2 for r in run)) for run in teacher_runs)
        teacher_rate=statistics.mean(math.sqrt(statistics.mean(r['steering_rate']**2 for r in run)) for run in teacher_runs)
        lqr_rate=statistics.mean(math.sqrt(statistics.mean(r['shadow_rate']**2 for r in run)) for run in teacher_runs)
        results[name]=dict(cases=len(references),episodes=len(traces),raw_physics_ticks=len(traces)*120,
            quality=protocol['quality'],objective=protocol['objective'],controller_kwargs=protocol['controller_kwargs'],
            reference_mean_episode_rmse_m=reference_rmse,teacher_mean_episode_rmse_m=teacher_rmse,
            mean_episode_rmse_gain_percent=100*(1-teacher_rmse/reference_rmse),
            eligible_teacher_contexts=len(eligible),selected_teacher_ticks=sum(r['sequence_plan_selected'] for r in rows),
            planned_eligible_contexts=sum(r['context']['planned'] for r in eligible),
            anchor_vs_lqr_mean_model_mixed_cost_gap_percent=dict(mean=statistics.mean(gaps),median=statistics.median(gaps),
                p90=percentile(gaps,.9),absolute_gap_below_1e_minus7_percent_count=sum(abs(v)<1e-7 for v in gaps),
                absolute_gap_below_1e_minus7_percent_fraction=statistics.mean(abs(v)<1e-7 for v in gaps)),
            minimum_across_models_mixed_cost_slack_percent_median=statistics.median(minimum_model_slacks),
            teacher_local_predicted_objective_gain_mean_percent=statistics.mean(local_gains),
            eligible_contexts_with_local_objective_diagnostic=len(local_gains),
            eligible_solver_status_counts=dict(statuses),
            eligible_solver_success_true_count=sum(r['teacher']['solver_success'] for r in eligible),
            selected_by_time=selected_by_time,
            mean_episode_heading_rms_ratio_vs_matched_lqr=teacher_heading/lqr_heading,
            mean_episode_rate_rms_ratio_vs_matched_lqr=teacher_rate/lqr_rate,
            teacher_mean_heading_within_110_percent_lqr=teacher_heading<=1.1*lqr_heading,
            teacher_mean_rate_within_110_percent_lqr=teacher_rate<=1.1*lqr_rate,
            provenance=provenance)
        if name=='teacher-development72':
            energies=[[r['error']**2 for r in run] for run in references]
            total=sum(sum(run) for run in energies);fractions={}
            for count in (2,4,10,20,40):
                prefix=sum(sum(run[:count]) for run in energies)
                fractions[str(count)]=dict(physical_time_through_s=count*.05,pooled_sse_fraction=prefix/total,
                    mean_episode_sse_fraction=statistics.mean(sum(run[:count])/sum(run) for run in energies))
            saturated=[0]*120;above_limit=0
            for run in references:
                previous=0.
                for tick,r in enumerate(run):
                    rate=(r['applied_steering']-previous)/.05;previous=r['applied_steering']
                    assert math.isclose(rate,r['steering_rate'],abs_tol=1e-10)
                    saturated[tick]+=abs(rate)>=.6-1e-8;above_limit+=abs(rate)>.6+1e-8
            first_second=sum(sum(run[:20]) for run in energies);late_fraction=1-first_second/total
            pooled_ratio=math.sqrt(1-late_fraction)
            prefix_mean_rmse=statistics.mean(math.sqrt(sum(run[:20])/120) for run in energies)
            results[name]['reference_error_decomposition']=dict(episodes=len(references),physical_dt_s=.05,
                physical_samples_per_episode=120,total_squared_lateral_error_m2=total,
                pooled_rmse_m=math.sqrt(total/(len(references)*120)),mean_episode_rmse_m=reference_rmse,
                prefix_energy_fractions=fractions,
                applied_command_rate_saturated_case_count_by_tick=saturated,
                applied_command_rate_above_original_point6_limit_count=above_limit,
                saturation_definition='abs((applied_steering[t]-applied_steering[t-1])/.05)>=.6-1e-8; previous=0 at first tick. Python applied commands, not native measured wheels.',
                conditional_fixed_prefix_post_one_second_error_zero=dict(
                    prefix_samples_held_fixed=20,late_samples_set_to_zero=100,late_sse_fraction=late_fraction,
                    new_to_old_pooled_rmse_ratio=pooled_ratio,optimistic_pooled_rmse_gain_percent=100*(1-pooled_ratio),
                    new_mean_episode_rmse_m=prefix_mean_rmse,
                    optimistic_mean_episode_rmse_gain_percent=100*(1-prefix_mean_rmse/reference_rmse),
                    formula='new_pooled_RMSE/old_pooled_RMSE=sqrt(1-late_SSE_fraction); gain_percent=100*(1-sqrt(1-late_SSE_fraction))',
                    scope='Algebraic error-zero ceiling conditional on keeping every first1s sample fixed. Not an upper bound over causal controllers that alter this prefix; zero tail is not asserted physically attainable.'))
    return dict(role='read_only_opened_case_rmse_opportunity_audit',opened_cases_only=True,
        proposals_generated=False,new_trajectories_generated=False,new_policies_trained=False,
        source_sha256={str(Path(__file__).relative_to(ROOT)):sha(__file__)},results=results,
        formulas=dict(mean_episode_rmse='mean_i sqrt(sum_t e_it^2/120)',
            pooled_rmse='sqrt(sum_i sum_t e_it^2/(episodes*120))',
            pooled_prefix_fraction='sum_i sum_{t<N} e_it^2 / sum_i sum_t e_it^2',
            mean_episode_prefix_fraction='mean_i (sum_{t<N} e_it^2 / sum_t e_it^2)',
            anchor_cost_gap_percent='100*(mean_3models(LQR mixedcost)-mean_3models(anchor mixedcost))/abs(mean_3models(LQR mixedcost))',
            ten_percent_rmse='For one fixed-length episode or pooledRMSE, 10% RMSE reduction requires1-.9^2=.19=19% SSE reduction. This does not identify pooledRMSE with mean episodeRMSE.'),
        interpretation_limits=['Every source case was previously opened for development; no prospective/generalization claim.',
            'Teacher trajectories are computed diagnostics, not PPO endpoints.',
            'Local SLSQP budget/iteration exhaustion is retained; these searches do not establish a global optimum or an impossibility ceiling.',
            'Local model mixedcost or finite_tracking objective gains are different quantities from realized whole-run RMSE gains.',
            'Keeping original local LQR heading/rate guards does not guarantee whole-run heading/rate qualification.',
            'Changing owner selection from mixedcost dominance over anchor to finite tracking may open a different feasible region while preserving original LQR guards, but no such experiment is performed here.',
            'Prefix energy shares and observed steering saturation describe these baseline trajectories, not all possible causal strategies.'])


def main():
    p=argparse.ArgumentParser();p.add_argument('--output',required=True,type=Path);args=p.parse_args()
    result=opportunity();args.output.parent.mkdir(parents=True,exist_ok=True)
    with args.output.open('x') as stream:json.dump(result,stream,indent=2,allow_nan=False);stream.write('\n')
    d=result['results']['teacher-development72']['reference_error_decomposition']
    print(json.dumps(dict(output=str(args.output),verified_opened_folders=len(result['results']),
        first_half_second_pooled_sse_fraction=d['prefix_energy_fractions']['10']['pooled_sse_fraction'],
        first_second_pooled_sse_fraction=d['prefix_energy_fractions']['20']['pooled_sse_fraction'],
        conditional_post_one_second_error_zero=d['conditional_fixed_prefix_post_one_second_error_zero']),indent=2),flush=True)


if __name__=='__main__':main()
